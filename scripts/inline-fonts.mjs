import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Regenerates lib/og-fonts.ts from assets/*.ttf.
 *
 * Cloudflare Workers has no filesystem, and fetching fonts from the Worker's
 * own domain fails once deployed (opennextjs-cloudflare#602). Inlining is the
 * only approach that behaves identically under `next dev`, `next build`, and
 * workerd. Run `npm run fonts` after replacing a .ttf.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const FACES = [
  ["ANTON", "Anton-Regular.ttf"],
  ["COURIER", "CourierPrime-Regular.ttf"],
  ["COURIER_BOLD", "CourierPrime-Bold.ttf"],
];

let out = `/**
 * Generated by \`npm run fonts\` from assets/*.ttf. Do not edit by hand.
 *
 * Inlined because Cloudflare Workers has no filesystem and a Worker cannot
 * fetch static assets from its own public domain once deployed.
 */

`;

for (const [name, file] of FACES) {
  const base64 = (await readFile(join(root, "assets", file))).toString("base64");
  out += `const ${name} =\n  "${base64}";\n\n`;
}

out += `function decode(base64: string): ArrayBuffer {
  return Uint8Array.from(atob(base64), (c) => c.charCodeAt(0)).buffer;
}

export const ogFonts = () => [
  { name: "Anton", data: decode(ANTON), weight: 400 as const, style: "normal" as const },
  { name: "Courier", data: decode(COURIER), weight: 400 as const, style: "normal" as const },
  { name: "Courier", data: decode(COURIER_BOLD), weight: 700 as const, style: "normal" as const },
];
`;

await writeFile(join(root, "lib", "og-fonts.ts"), out);
console.log(`lib/og-fonts.ts — ${(out.length / 1024).toFixed(0)} KB`);
